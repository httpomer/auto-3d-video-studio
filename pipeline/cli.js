#!/usr/bin/env node
// Production CLI.
//   node pipeline/cli.js catalog              → refresh docs/SCENES.md (scene template reference)
//   node pipeline/cli.js validate <slug>      → check projects/<slug>/video.json
//   node pipeline/cli.js stills <slug>        → contact sheets of every shot for visual review
//   node pipeline/cli.js produce <slug>       → narration → render → mix → final MP4 + thumbnail + metadata
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, CACHE, projectDir, ensureDir } from './paths.js';
import { buildTimeline, flattenShots, wordsOf, estimateDur } from './timeline.js';
import { startServer } from './server.js';
import { openEngine } from './browser.js';
import { runFF } from './audio-util.js';

const [cmd, ...rest] = process.argv.slice(2);
const slug = rest.find((a) => !a.startsWith('--'));
const opt = Object.fromEntries(rest.filter((a) => a.startsWith('--')).map((a) => { const i = a.indexOf('='); return i < 0 ? [a.slice(2), true] : [a.slice(2, i), a.slice(i + 1)]; }));
const log = (...a) => console.log(...a);
const OVERLAYS = ['title', 'chapter', 'lower', 'stat', 'callout', 'bullets', 'quote', 'tag', 'source', 'thumb'];
const TRANSITIONS = ['cut', 'fade', 'dip', 'wipe', 'zoom', 'push'];

async function getCatalog(framingQueries) {
  const srv = await startServer();
  const eng = await openEngine(srv.port, { width: 640, height: 360, id: 'catalog' });
  try {
    const cat = await eng.page.evaluate(() => window.__catalog());
    if (framingQueries) cat.framingsFor = await eng.page.evaluate((l) => window.__framings(l), framingQueries);
    return cat;
  } finally { await eng.close(); await srv.close(); }
}

async function catalog() {
  const cat = await getCatalog();
  cat.sort((a, b) => a.name.localeCompare(b.name));
  ensureDir(CACHE); fs.writeFileSync(path.join(CACHE, 'catalog.json'), JSON.stringify(cat, null, 1));
  let md = '# Scene template reference\n\nGenerated by `npm run catalog` — do not edit by hand.\n\n';
  for (const c of cat) {
    md += `## \`${c.name}\`\n\n${c.description}\n\n`;
    if (Object.keys(c.params).length) md += '| param | meaning |\n|---|---|\n' + Object.entries(c.params).map(([k, v]) => `| \`${k}\` | ${String(v).replace(/\|/g, '\\|')} |`).join('\n') + '\n\n';
    md += `**Framings:** ${c.framings.map((f) => '`' + f + '`').join(', ')}\n\n`;
    md += '**Sample params:**\n```json\n' + JSON.stringify(c.sample) + '\n```\n\n';
  }
  ensureDir(path.join(ROOT, 'docs')); fs.writeFileSync(path.join(ROOT, 'docs', 'SCENES.md'), md);
  log(`${cat.length} scene templates → docs/SCENES.md`);
  return cat;
}

function loadVideo() {
  if (!slug) { console.error('Missing project slug.'); process.exit(1); }
  const dir = projectDir(slug), file = path.join(dir, 'video.json');
  if (!fs.existsSync(file)) { console.error(`Not found: ${file}`); process.exit(1); }
  let video;
  try { video = JSON.parse(fs.readFileSync(file, 'utf8')); } catch (e) { console.error(`video.json is not valid JSON: ${e.message}`); process.exit(1); }
  return { dir, video };
}

async function validate(video, { quiet = false } = {}) {
  const { shots, chapters } = flattenShots(video);
  // framings can depend on params → ask the engine for each shot's actual framing names
  let firstParams = {};
  const queries = shots.map((sh) => { if (!sh.continues) firstParams = sh.params || {}; return [sh.scene, { ...firstParams, ...(sh.params || {}) }]; });
  const cat = await getCatalog(queries);
  const byName = Object.fromEntries(cat.map((c) => [c.name, c]));
  const errors = [], warns = [];
  if (!video.meta?.title) errors.push('meta.title is missing');
  if (!shots.length) errors.push('no shots');
  const ids = new Set();
  let words = 0, est = 0, prevScene = null, run = 0;
  const usage = {};
  shots.forEach((s, i) => {
    const where = `shot ${i + 1} (${s.id})`;
    if (ids.has(s.id)) errors.push(`${where}: duplicate id`); ids.add(s.id);
    const tpl = byName[s.scene];
    if (!tpl) { errors.push(`${where}: unknown scene "${s.scene}"`); return; }
    usage[s.scene] = (usage[s.scene] || 0) + 1;
    if (s.continues && i > 0 && shots[i - 1].scene !== s.scene) errors.push(`${where}: "continues" but previous shot uses a different scene`);
    if (s.continues && s.chapterStart && i > 0) warns.push(`${where}: continues across a chapter boundary`);
    const cam = s.camera;
    const fr = Array.isArray(cat.framingsFor?.[i]) ? cat.framingsFor[i] : tpl.framings;
    if (cat.framingsFor?.[i]?.error) errors.push(`${where}: params break the scene's framings (${cat.framingsFor[i].error})`);
    if (cam) for (const k of ['from', 'to']) { const v = typeof cam === 'string' ? cam : cam[k]; if (typeof v === 'string' && !fr.includes(v)) errors.push(`${where}: camera.${k} "${v}" is not a framing of ${s.scene} (${fr.join(', ')})`); }
    for (const o of s.overlays || []) if (!OVERLAYS.includes(o.type)) errors.push(`${where}: unknown overlay type "${o.type}"`);
    const tr = typeof s.transition === 'string' ? s.transition : s.transition?.type;
    if (tr && !TRANSITIONS.includes(tr)) errors.push(`${where}: unknown transition "${tr}"`);
    const w = wordsOf(s.narration).length; words += w;
    const d = w ? estimateDur(s.narration) + 0.4 : (s.duration ?? 3); est += d;
    if (!w && s.duration == null) warns.push(`${where}: no narration and no duration (defaults to 3 s)`);
    if (d > 13) warns.push(`${where}: ~${d.toFixed(0)} s on one shot — split it or add a continued shot with a new camera`);
    if (w && d < 2.2) warns.push(`${where}: only ~${d.toFixed(1)} s — very short`);
    run = s.scene === prevScene ? run + d : d; prevScene = s.scene;
    if (run > 30) warns.push(`${where}: the "${s.scene}" scene has been on screen for ~${run.toFixed(0)} s in a row`);
  });
  for (const [k, v] of Object.entries(usage)) if (v / shots.length > 0.2 && shots.length > 20) warns.push(`scene "${k}" is used in ${v} of ${shots.length} shots — vary the visuals`);
  if (!quiet || errors.length) {
    log(`\n"${video.meta?.title}" — ${chapters.length} chapters, ${shots.length} shots, ${Object.keys(usage).length} different scenes`);
    log(`narration: ${words} words ≈ ${(est / 60).toFixed(1)} min (estimate; exact length comes from the voice audio)`);
    for (const w of warns) log('  warning: ' + w);
    for (const e of errors) log('  ERROR: ' + e);
    log(errors.length ? `\n${errors.length} error(s) — fix before producing.` : `OK${warns.length ? ` with ${warns.length} warning(s)` : ''}.`);
  }
  return { errors, warns, words, est };
}

const srtTime = (t) => { const ms = Math.round(t * 1000); const h = Math.floor(ms / 3600000), m = Math.floor(ms / 60000) % 60, s = Math.floor(ms / 1000) % 60; return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}`; };
const ytTime = (t) => { const m = Math.floor(t / 60), s = Math.floor(t % 60); return `${m}:${String(s).padStart(2, '0')}`; };

async function produce() {
  const { dir, video } = loadVideo();
  const t0 = Date.now();
  const build = ensureDir(path.join(dir, 'build')), outDir = ensureDir(path.join(dir, 'output'));
  const { synthesizeNarration } = await import('./tts.js');
  const { renderVideo, renderFramePng } = await import('./render.js');
  const { buildSoundtrack } = await import('./audio.js');

  log('[1/7] Validating storyboard');
  const v = await validate(video, { quiet: true });
  if (v.errors.length) process.exit(1);

  log('[2/7] Generating narration');
  const voice = await synthesizeNarration(video, dir, { log });

  log('[3/7] Building timeline');
  const tl = buildTimeline(video, voice);
  fs.writeFileSync(path.join(build, 'timeline.json'), JSON.stringify(tl));
  log(`  ${tl.shots.length} shots, ${ytTime(tl.duration)} total, ${tl.captions.length} caption cues`);
  if (opt['no-captions']) tl.captions = [];

  log('[4/7] Mixing soundtrack (voice + music + sound design)');
  const mix = await buildSoundtrack(video, tl, voice, dir, build, { log });

  log('[5/7] Rendering 3D animation');
  const silent = path.join(build, 'video.mp4');
  await renderVideo(tl, silent, build, { workers: parseInt(opt.workers ?? '3'), crf: parseInt(opt.crf ?? '17'), log });

  log('[6/7] Final assembly');
  const final = path.join(outDir, `${video.meta.slug || slug}.mp4`);
  await runFF(['-i', silent, '-i', mix, '-map', '0:v', '-map', '1:a', '-c:v', 'copy', '-c:a', 'aac', '-b:a', '256k', '-ar', '48000', '-t', tl.duration.toFixed(3), '-movflags', '+faststart', final]);

  log('[7/7] Subtitles, thumbnail, YouTube metadata');
  const full = buildTimeline(video, voice); // captions even when not burned in
  fs.writeFileSync(path.join(outDir, 'subtitles.srt'), full.captions.map((c, i) => `${i + 1}\n${srtTime(c.start)} --> ${srtTime(c.end)}\n${c.lines.map((l) => l.map((x) => x.w).join(' ')).join('\n')}\n`).join('\n'));
  await makeThumbnail(video, tl, outDir, renderFramePng);
  const m = video.meta;
  const chapters = tl.chapters.filter((c) => c.title && c.start != null);
  let desc = (m.description || '').trim() + '\n\n';
  if (chapters.length >= 3) desc += 'Chapters:\n' + chapters.map((c, i) => `${ytTime(i === 0 ? 0 : c.start)} ${c.title}`).join('\n') + '\n\n';
  if (m.sources?.length) desc += 'Sources:\n' + m.sources.map((s) => `- ${s}`).join('\n') + '\n\n';
  if (m.hashtags?.length) desc += m.hashtags.map((h) => (h.startsWith('#') ? h : '#' + h)).join(' ') + '\n';
  const tags = m.tags || [];
  const block = (title, body) => (body ? `${title}\n${body}\n\n` : '');
  const lang = m.language || 'English';
  const portrait = tl.height > tl.width;
  const upload = [
    m.category && `Category: ${m.category}`,
    `Video language: ${lang} · Captions: upload subtitles.srt as ${lang} subtitles`,
    'Audience: not made for kids',
    m.playlist && `Playlist: ${m.playlist}`,
    (portrait ? 'Format: YouTube Short (9:16) — thumbnail.jpg is a 1080×1920 cover; pick it in the Shorts upload screen' : m.thumbnail?.variants?.length ? `Thumbnail: thumbnail.jpg — add thumbnail_b.jpg${m.thumbnail.variants.length > 1 ? ' and thumbnail_c.jpg' : ''} in YouTube Studio → Test & Compare` : 'Thumbnail: thumbnail.jpg (1280×720)'),
    'Chapters: the timestamps in the description create YouTube chapters automatically',
  ].filter(Boolean).join('\n');
  fs.writeFileSync(path.join(outDir, 'youtube.txt'),
    block('TITLE', m.title) +
    block('ALTERNATIVE TITLES (for A/B testing)', (m.altTitles || []).join('\n')) +
    block('DESCRIPTION', desc.trim()) +
    block(`TAGS (${tags.join(',').length}/500 characters)`, tags.join(', ')) +
    block('PINNED COMMENT', m.pinnedComment) +
    block('UPLOAD SETTINGS', upload));

  const size = fs.statSync(final).size / 1048576;
  log(`\nDONE in ${((Date.now() - t0) / 60000).toFixed(1)} min`);
  log(`  video:     ${final}  (${ytTime(tl.duration)}, ${size.toFixed(0)} MB, ${tl.width}x${tl.height}@${tl.fps})`);
  log(`  thumbnail: ${path.join(outDir, 'thumbnail.jpg')}`);
  log(`  subtitles: ${path.join(outDir, 'subtitles.srt')}`);
  log(`  metadata:  ${path.join(outDir, 'youtube.txt')}`);
}

/** Channel-wide brand settings (name, colour, thumbnail grade) from channel.json. */
function loadChannel() {
  const f = path.join(ROOT, 'channel.json');
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {};
}

async function makeThumbnail(video, tl, outDir, renderFramePng) {
  const ch = loadChannel(), cth = ch.thumbnail || {};
  const base = video.meta.thumbnail || {};
  const first = flattenShots(video).shots[0];
  // variants share the scene/camera and override text, colour or graphics — for YouTube "Test & Compare"
  const variants = [base, ...(base.variants || []).map((v) => ({ ...base, ...v }))];
  const files = [];
  const portrait = (video.meta.height ?? 1080) > (video.meta.width ?? 1920); // Shorts get a 9:16 cover
  for (let i = 0; i < variants.length; i++) {
    const th = variants[i];
    const shot = {
      id: 'thumb', scene: th.scene || first.scene, params: th.params || first.params || {}, camera: th.camera, duration: 8, hideLabels: th.sceneLabels !== true,
      overlays: [{ type: 'thumb', at: 0, text: th.text || video.meta.title, sub: th.sub, highlight: th.highlight, hot: th.hot || cth.hot, side: th.side,
        arrow: th.arrow, circle: th.circle, callouts: th.callouts, size: th.size, width: th.width, y: th.y, maxLines: th.maxLines }],
      look: { ...(cth.look || {}), ...(th.look || {}) },
    };
    const ttl = buildTimeline({ meta: { ...video.meta, theme: th.theme || cth.theme || video.meta.theme, themeOverrides: th.themeOverrides || video.meta.themeOverrides }, shots: [shot] }, {}, portrait ? { width: 1080, height: 1920 } : { width: 1920, height: 1080 });
    const name = i === 0 ? 'thumbnail' : `thumbnail_${String.fromCharCode(97 + i)}`;
    const png = path.join(outDir, name + '.png');
    await renderFramePng(ttl, th.time ?? 5, png);
    await runFF(['-i', png, '-vf', portrait ? 'scale=1080:1920:flags=lanczos' : 'scale=1280:720:flags=lanczos', '-q:v', '2', path.join(outDir, name + '.jpg')]);
    fs.rmSync(png, { force: true });
    files.push(path.join(outDir, name + '.jpg'));
  }
  return files;
}

async function thumbnailOnly() {
  const { dir, video } = loadVideo();
  const { renderFramePng } = await import('./render.js');
  const files = await makeThumbnail(video, null, ensureDir(path.join(dir, 'output')), renderFramePng);
  for (const f of files) log('thumbnail: ' + f);
}

async function stills() {
  const { dir, video } = loadVideo();
  const v = await validate(video);
  if (v.errors.length) process.exit(1);
  let voice = {};
  // use real narration timing when clips already exist (or when --voice asks to generate them)
  if (opt.voice || fs.existsSync(path.join(dir, 'audio', 'voice'))) { const { synthesizeNarration } = await import('./tts.js'); voice = await synthesizeNarration(video, dir, { log }); }
  const tl = buildTimeline(video, voice);
  const { renderStills } = await import('./render.js');
  const only = opt.shots ? String(opt.shots).split(',').map((x) => parseInt(x)).filter(Boolean) : null;
  const files = await renderStills(tl, path.join(dir, 'build', 'stills'), { log, at: parseFloat(opt.at ?? '0.6'), only });
  for (const f of files) log('  ' + f);
}

try {
  if (['stills', 'produce', 'thumbnail'].includes(cmd)) { const { ensureAssets } = await import('./assets.js'); await ensureAssets({ log }); }
  if (cmd === 'catalog') await catalog();
  else if (cmd === 'validate') { const { video } = loadVideo(); const v = await validate(video); process.exitCode = v.errors.length ? 1 : 0; }
  else if (cmd === 'stills') await stills();
  else if (cmd === 'thumbnail') await thumbnailOnly();
  else if (cmd === 'produce') await produce();
  else { console.log('usage: node pipeline/cli.js <catalog|validate|stills|produce|thumbnail> [slug] [--workers=3] [--crf=17] [--no-captions]'); process.exitCode = 1; }
} catch (e) { console.error('\nFAILED: ' + (e?.stack || e)); process.exit(1); }
